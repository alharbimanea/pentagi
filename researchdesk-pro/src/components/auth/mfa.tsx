"use client";

import { useRouter } from "next/navigation";
import { useEffect, useState } from "react";
import { Alert } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Field, Input } from "@/components/ui/input";
import type { Dictionary } from "@/lib/i18n";
import { browserClient } from "@/lib/supabase/browser";

type Mode = { kind: "loading" } | { kind: "enroll"; factorId: string; qr: string; secret: string } | { kind: "challenge"; factorId: string } | { kind: "done" };

// TOTP enrolment and step-up through Supabase Auth MFA. A verified challenge
// upgrades the session to aal2, which is what is_admin() checks in Postgres.
export function MfaPanel({ dict, next }: { dict: Dictionary; next: string }) {
  const router = useRouter();
  const [mode, setMode] = useState<Mode>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    const supabase = browserClient();
    (async () => {
      const [{ data: aal }, { data: factors }] = await Promise.all([supabase.auth.mfa.getAuthenticatorAssuranceLevel(), supabase.auth.mfa.listFactors()]);
      if (aal?.currentLevel === "aal2") return setMode({ kind: "done" });
      const verified = factors?.totp.find((f) => f.status === "verified");
      if (verified) return setMode({ kind: "challenge", factorId: verified.id });
      for (const stale of factors?.all.filter((f) => f.status === "unverified") ?? []) await supabase.auth.mfa.unenroll({ factorId: stale.id });
      const { data, error } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: `ResearchDesk ${new Date().toISOString().slice(0, 10)}` });
      if (error || !data) return setError(dict.errors.generic);
      setMode({ kind: "enroll", factorId: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
    })();
  }, [dict.errors.generic]);

  async function verify(factorId: string) {
    setBusy(true);
    setError(null);
    const supabase = browserClient();
    const { error } = await supabase.auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
    setBusy(false);
    if (error) return setError(dict.auth.mfaInvalid);
    setMode({ kind: "done" });
    router.replace(next);
    router.refresh();
  }

  if (mode.kind === "loading") return <p className="text-sm text-muted-foreground">…</p>;
  if (mode.kind === "done") return <Alert tone="success">{dict.auth.mfaEnabled}</Alert>;

  return (
    <div className="space-y-4">
      {error ? <Alert tone="error">{error}</Alert> : null}
      {mode.kind === "enroll" ? (
        <>
          <p className="text-sm">{dict.auth.mfaScan}</p>
          {/* The QR is an SVG data URI generated by Supabase for this enrolment. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={mode.qr} alt="" width={180} height={180} className="rounded border bg-white p-2" />
          <p className="text-xs text-muted-foreground">
            {dict.auth.mfaSecret}: <code className="break-all">{mode.secret}</code>
          </p>
        </>
      ) : null}
      <form
        className="flex items-end gap-2"
        onSubmit={(e) => {
          e.preventDefault();
          void verify(mode.factorId);
        }}
      >
        <Field label={dict.auth.mfaCode} htmlFor="code" className="flex-1">
          <Input id="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required value={code} onChange={(e) => setCode(e.target.value)} />
        </Field>
        <Button type="submit" disabled={busy}>
          {dict.auth.mfaVerify}
        </Button>
      </form>
    </div>
  );
}
